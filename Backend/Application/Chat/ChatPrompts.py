            "1. 简要分析故障场景、可能的故障原因及其逻辑关系。\n"
            "2. 如果上下文文档中有相关信息，引用关键内容辅助分析。\n"
            "3. 严禁输出 JSON、代码块或任何故障树数据结构。\n"
            "4. 不必描述节点和连接的具体结构，故障树图会自动展示。\n"
            "5. 如果信息不够充分，在末尾提出补充问题引导用户。"
